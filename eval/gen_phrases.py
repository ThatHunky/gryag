"""Generate gryag/phrases.py once, offline.

The bot must not call the model to tell a joke — that is the V3 rule. So the jokes are
written ahead of time, by a bigger model than the one that speaks, and committed. Run this
again only to refresh the pool:

    .venv/bin/python eval/gen_phrases.py

It overwrites gryag/phrases.py. Read the diff before committing it: this is the one place
where model output ships to a real chat without anybody reading it first.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from dotenv import load_dotenv
from google import genai
from google.genai import types

ROOT = Path(__file__).resolve().parent.parent
PERSONA = ROOT / "eval" / "persona-v3.txt"
TARGET = ROOT / "gryag" / "phrases.py"

MODEL = "gemini-3.1-pro-preview"

POOLS = {
    "WARMUP": (
        60,
        "Рядки-«прогріви», які бот пише ПЕРЕД тим, як оголосити підараса дня. "
        "Створюють паузу й інтригу. Нікого не називають, без плейсхолдерів. "
        "Приклади настрою: «зараз подивимось», «вже гортаю список», «шукаю за запахом». "
        "Кожен рядок — до 60 символів.",
    ),
    "VERDICT": (
        60,
        "Рядки-присуди: оголошення переможця. Кожен МУСИТЬ містити рівно один "
        "плейсхолдер {who} — саме у фігурних дужках, латиницею. "
        "Приклад: «сьогодні це {who}, вітаю». Кожен рядок — до 90 символів.",
    ),
    "ALREADY": (
        30,
        "Рядки для випадку, коли на сьогодні підараса вже обрано і хтось питає вдруге. "
        "Кожен МУСИТЬ містити рівно один плейсхолдер {who}. "
        "Настрій: трохи втомлений. Приклад: «та {who} же, я вже казав». До 90 символів.",
    ),
    "DIGEST": (
        40,
        "Рядки-підписи під зведенням про підтверджені втрати ворога від Сил безпілотних "
        "систем. ЦЕ НЕ ЖАРТИ. Не жартуй про загиблих і не коментуй цифри. "
        "Коментуй роботу: «нормальна робота», «гарний день у хлопців», «так тримати». "
        "Стримано, без пафосу й без емодзі. До 50 символів.",
    ),
}

SCHEMA = {
    "type": "object",
    "properties": {"lines": {"type": "array", "items": {"type": "string"}}},
    "required": ["lines"],
}


def generate(client: genai.Client, persona: str, count: int, brief: str) -> list[str]:
    response = client.models.generate_content(
        model=MODEL,
        contents=(
            f"{brief}\n\nНапиши рівно {count} різних варіантів. "
            "Українською, у голосі персонажа, описаного в системній інструкції. "
            "Не нумеруй. Не повторюйся."
        ),
        config=types.GenerateContentConfig(
            system_instruction=persona,
            response_mime_type="application/json",
            response_schema=SCHEMA,
            temperature=1.2,
        ),
    )
    lines = json.loads(response.text)["lines"]
    return [line.strip() for line in lines if line.strip()]


def valid(name: str, line: str) -> bool:
    if "\n" in line:
        return False
    if name in ("VERDICT", "ALREADY"):
        return line.count("{who}") == 1 and line.count("{") == 1
    return "{" not in line


def main() -> None:
    load_dotenv(ROOT / ".env")
    client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
    persona = PERSONA.read_text()

    pools: dict[str, list[str]] = {}
    for name, (count, brief) in POOLS.items():
        raw = generate(client, persona, count, brief)
        kept: list[str] = []
        for line in raw:
            if valid(name, line) and line not in kept:
                kept.append(line)
        print(f"{name}: asked {count}, got {len(raw)}, kept {len(kept)}")
        if len(kept) < 20:
            raise SystemExit(f"{name} came back too thin ({len(kept)}); run it again")
        pools[name] = kept

    body = [
        '"""Generated by eval/gen_phrases.py. Do not edit by hand — regenerate instead.',
        "",
        "The bot must not call a model to tell a joke, so the jokes are written ahead of",
        'time and shipped as data."""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for name, lines in pools.items():
        body.append(f"{name}: tuple[str, ...] = (")
        body.extend(f"    {line!r}," for line in lines)
        body.append(")")
        body.append("")
    body.extend(
        [
            "",
            "def pick(pool: tuple[str, ...], seed: int) -> str:",
            '    """Deterministic for a given seed.',
            "",
            "    The seed is the thing being described — a chat and a day, say — so the same",
            "    event reads the same on every retry, and two events a second apart do not.",
            '    """',
            "    return pool[seed % len(pool)]",
            "",
        ]
    )
    TARGET.write_text("\n".join(body))
    print(f"wrote {TARGET} ({sum(len(v) for v in pools.values())} lines)")


if __name__ == "__main__":
    main()
